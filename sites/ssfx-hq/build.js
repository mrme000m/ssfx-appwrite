/**
 * sites/ssfx-hq/build.js
 * Build-time config generator. Overwrites config.js with env vars when run inside Appwrite build.
 */

const fs = require('fs');
const path = require('path');

const defaults = {
  endpoint: 'https://sgp.cloud.appwrite.io/v1',
  projectId: '6a22a362002b9ae880bb',
  authDomain: 'https://auth.mrme.tech',
  pinDomain: 'https://pin.mrme.tech',
  apiBase: 'https://api.mrme.tech',
  v2ApiBase: 'https://api.mrme.tech',
  marketBase: 'https://market.mrme.tech',
  dataserviceBase: 'https://market.mrme.tech',
  aiBase: 'https://ai.mrme.tech',
  agentHarnessBase: 'https://ai.mrme.tech',
  researchBase: 'https://research.mrme.tech',
  pplxAgentBase: 'https://research.mrme.tech',
  databaseId: 'slwp_platform',
  marketDatabaseId: 'market_data',
  siteUrl: 'https://app.mrme.tech',
  adminKey: '',
  v2AdminKey: '',
  marketApiKey: '',
  dataserviceApiKey: '',
};

// Map of config keys to additional environment variable names to try
const envKeyAliases = {
  marketApiKey: ['DATA_SERVICE_API_KEY', 'DATASERVICE_API_KEY', 'MARKET_API_KEY'],
  dataserviceApiKey: ['DATA_SERVICE_API_KEY', 'DATASERVICE_API_KEY'],
  adminKey: ['V2_ADMIN_KEY', 'ADMIN_API_KEY', 'V2ADMIN_KEY'],
  v2AdminKey: ['V2_ADMIN_KEY', 'ADMIN_API_KEY', 'V2ADMIN_KEY'],
  apiBase: ['API_BASE_URL', 'V2_API_BASE'],
  marketBase: ['MARKET_BASE_URL', 'DATA_SERVICE_URL'],
  aiBase: ['AI_BASE_URL', 'AGENT_HARNESS_BASE'],
  researchBase: ['RESEARCH_BASE_URL', 'PPLX_AGENT_BASE'],
  agentHarnessBase: ['AGENT_HARNESS_BASE'],
};

const config = {};
for (const [k, v] of Object.entries(defaults)) {
  // Try camelCase version first
  const camelKey = k.toUpperCase();
  
  // Try environment variable aliases (e.g., V2_ADMIN_KEY, DATA_SERVICE_API_KEY)
  const aliases = envKeyAliases[k] || [];
  
  // Build list of env var names to try: camelCase, snake_case, and aliases
  const envKeys = [camelKey];
  
  // Convert camelCase to UPPER_SNAKE_CASE (e.g., v2AdminKey -> V2_ADMIN_KEY)
  const snakeKey = k.replace(/([A-Z])/g, (match, p1, offset) => {
    return offset > 0 ? '_' + p1 : p1;
  }).toUpperCase();
  envKeys.push(snakeKey);
  
  // Add any aliases
  envKeys.push(...aliases);
  
  // Find the first matching environment variable
  let value = v;
  for (const envKey of envKeys) {
    if (process.env[envKey]) {
      value = process.env[envKey];
      break;
    }
  }
  config[k] = value;
}

const out = `/**\n * SSFX HQ — consolidated command platform configuration\n * Generated by build.js from environment variables.\n */\nwindow.APP_CONFIG = ${JSON.stringify(config, null, 2)};\n`;

const target = path.join(__dirname, 'config.js');
fs.writeFileSync(target, out, 'utf8');
console.log(`[build] wrote ${target}`);
